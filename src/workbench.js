/** 一个任务节点 → 一行（判据、冻结、打回、产出物、交卷进度、判活标注）。 */
function 任务行(node, 实例活动) {
  const 复核对象 = Array.isArray(node.复核对象) ? node.复核对象 : [];
  const 只读历史 = 是只读旧会审(node);
  return {
    id: node.id,
    描述: node.描述,
    状态: node.状态,
    负责人: node.负责人 ?? [],
    // v2 条目18：新节点不造 `模式: null` 空壳；历史事件有值才投影（只读保留）。
    ...(node.模式 != null ? { 模式: node.模式 } : {}),
    ...(只读历史 ? { 只读历史: true, 写入说明: '旧会审已退出任务图；仅保留历史，不改不迁移，不提供写命令。' } : {}),
    判据: node.判据 ?? [],
    判据冻结: node.判据冻结 === true,
    依赖: node.依赖 ?? [],
    // v2 条目6：显式复核对象（复核任务验哪一单）。空列表不投影，避免空壳。
    ...(复核对象.length > 0 ? { 复核对象 } : {}),
    // v2 条目11：已绑实例（「此刻谁在干」）。复核读域按「绑定含本实例」判，
    // 所以投影必须带它——否则 workbench 读面会算不出复核员的任务作用域。
    ...(Array.isArray(node.绑定) && node.绑定.length > 0
      ? { 绑定: node.绑定.map((b) => ({ 实例: b?.实例 ?? null, 岗位: b?.岗位 ?? null })) }
      : {}),
    打回次数: node.打回次数 ?? 0,
    产物: node.产出物引用 ?? [],
    交卷: 交卷进度(node),
    // 补修K（条目4）：复核「过」只出票、不代 Lead 采纳——这一行必须把**真票**与命令一起
    // 给出来（指路不能只有内部字段）；旧账「复核即采纳」且无 Lead 承接的，标 需Lead确认。
    ...(node.待采纳
      ? {
        待采纳: node.待采纳,
        ...(!只读历史 ? { 采纳命令: `/mind task_accept id=${node.id} 票=${node.待采纳.票}` } : {}),
      }
      : {}),
    ...(node.采纳 ? { 采纳: node.采纳 } : {}),
    ...(node.需Lead确认 === true ? { 需Lead确认: true, ...(!只读历史 ? { 确认命令: `/mind task_accept id=${node.id}` } : {}) } : {}),
    // 判活标注（派活闭环 2026-10-15）：只在「已派发/执行中」窗口报——复核窗口之后
    // 「没人干活」已由打回/待决那些状态自己说话。口径 = 审计链零行（被拒也算活动——
    // 死物不会敲门）；索引里没有的负责人（未登记）同样报「未见活动」，与派发闸同向。
    ...(实例活动 && 进行中.has(node.状态)
      ? { 负责人无活动: (node.负责人 ?? []).filter((id) => !实例活动[id] || 实例活动[id].最近活动于 == null) }
      : {}),
    ...(node.升级 ? { 升级: node.升级 } : {}),
    ...(node.待决原因 ? { 待决原因: node.待决原因 } : {}),
  };
}

/**
 * 交卷进度：**应交**看负责人实例名单（绑定优先、历史负责人回落），**已交**看有几个人的独立答案。
 * 两者都来自任务图事件流，所以是纯投影（§9 会审解锁就靠这个判据）。
 * 「齐」的判据只有一处实现（tasks.js 的 全员已交，按人核对）；旧 bus_unlock 已退役，
 * 现在同一把尺服务 debate_unlock / 盲评遮罩 / 复核读域的齐卷判定。
 */
function 交卷进度(node) {
  // 应交按**负责人实例名单**（绑定优先、历史负责人回落）——与 全员已交 同一单源，
  // 否则面板会报「应交 2、齐卷 1」而实际是同一份名单在两种口径下算出来的。
  const 应交 = 负责人实例名单(node).length;
  const 已交 = (node.独立答案 ?? []).length;
  return { 已交, 应交, 齐: 全员已交(node) };
}

