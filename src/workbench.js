/**
 * 共享工作台（§7「当前状态的唯一视图」）。
 *
 * §14.2 在目录上给它标了 ⚠️：**无存储，纯投影**。
 * 于是本文件只有纯函数、没有 IO——这本身就是「不许当第二事实源」的技术保证：
 * 它在磁盘上没有任何东西可以被别的组件误认成真相。
 *
 * 显示什么，是**从设计推出来的**，不是挑好看的：
 *
 * | 这块 | 依据 |
 * |---|---|
 * | 待你决定 | 待决项是设计里唯一点名「工作台把它投影出来」的东西（§7 存储归属） |
 * | 任务节点 | 投影的两个来源之一（§7：「能从任务图 + 日志重算」） |
 * | 会审 | §10 反趋同：交卷进度 · 独立答案 · 分歧清单 · 反例面 · 零分歧 |
 * | 审计尾 | 投影的另一个来源；它是事实记录，不是讨论 |
 * | 状态条 | 当前状态；但取自**已有记录**，不现场重跑 |
 * | 记忆读数 | 验账用的当前状态（存量 + 近段新增/晋升），不是基础设施计数——人由此一眼确认「记账在正常发生」，不必翻账本 |
 * | 消息总线 | ⑦（2026-10-11）：全部线程的规模 + 最新消息扫描行 + 未投递数——「有没有人想说话」一眼可见；**会审节点与开了讨论的节点**的线程按盲评口径只给规模行（名单口径与会审行同口径，判定键走 `线程等价键()`） |
 * | 项目清单 | 面板项目解析修正（2026-10-11）：磁盘上出现过的项目键 + 各项目规模——面板默认只显示一个项目，没有这份清单时「活账在别的项目下」会表现成「面板永远一片空白」 |
 *
 * 而**不显示**：八件基础设施的其余计数（那是系统元数据，不是当前状态，且与 `mind status` 重复）、
 * 主干环路 stepper（§8 的环路是**流程定义**，画成常驻进度条永远停在某一格，信息量为零）、
 * 会审讨论正文与成员归属（§10 盲评：未交齐不揭名，遮罩做在投影层）。
 */
