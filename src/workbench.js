/** 一个任务节点 → 一行（判据、冻结、打回、产出物、交卷进度、判活标注）。 */
function 任务行(node, 实例活动) {
  return {
    id: node.id,
    描述: node.描述,
    状态: node.状态,
    负责人: node.负责人 ?? [],
    模式: node.模式 ?? null,
    判据: node.判据 ?? [],
    判据冻结: node.判据冻结 === true,
    依赖: node.依赖 ?? [],
    打回次数: node.打回次数 ?? 0,
    产物: node.产出物引用 ?? [],
    交卷: 交卷进度(node),
    // 判活标注（派活闭环 2026-10-15）：只在「已派发/执行中」窗口报——复核窗口之后
    // 「没人干活」已由打回/待决那些状态自己说话。口径 = 审计链零行（被拒也算活动——
    // 死物不会敲门）；索引里没有的负责人（未登记）同样报「未见活动」，与派发闸同向。
    ...(实例活动 && 进行中.has(node.状态)
      ? { 负责人无活动: (node.负责人 ?? []).filter((id) => !实例活动[id] || 实例活动[id].最近活动于 == null) }
      : {}),
    ...(node.升级 ? { 升级: node.升级 } : {}),
    ...(node.待决原因 ? { 待决原因: node.待决原因 } : {}),
  };
}

/**
 * 交卷进度：**应交**看负责人人数，**已交**看有几个人的独立答案。
 * 两者都来自任务图事件流，所以是纯投影（§9 会审解锁就靠这个判据）。
 * 「齐」的判据只有一处实现（tasks.js 的 全员已交，按人核对）——与 debate_open /
 * bus_unlock 同一把尺；计数判据会被「非负责人垫一份」骗开（2026-10-12 评审 P2-5）。
 */
function 交卷进度(node) {
  const 应交 = (node.负责人 ?? []).length;
  const 已交 = (node.独立答案 ?? []).length;
  return { 已交, 应交, 齐: 全员已交(node) };
}

/**
 * 一次会审 → 一块。**独立答案按人留**（§10：N 份独立答案 + 分歧清单）。
 *
 * 盲标与揭名：未交齐时**答案行只给盲标**（成员、结论、反例面、产出物引用都不出）；
 * 交齐后全给。这条规矩是 §10 的，不是界面的——投影照做，界面照显示。
 *
 * 为什么遮罩要做在投影这一层（W3 批2·2026-10-09）：此前只给一个 `揭名: false` 提示字段，
 * 真名与结论照样投影出去——「3/3 之前看不到任何人的答案」于是变成一句靠消费者自觉的
 * 君子协定。方案收敛的判据是「看不到」，所以投影必须真的不给，而不是给一个标记等人遵守。
 * 注意：零分歧判定仍用**全量**答案现算（判定是机制读数，不是内容；`零分歧` 字段照旧投影）。
 *
 * @param {object} node
 * @param {object[]} [线程消息] 该节点讨论线程的折叠消息（组装层喂的，纯投影不取数）
 */
function 会审行(node, 线程消息 = []) {
  const 进度 = 交卷进度(node);
  const 全量答案 = node.独立答案 ?? [];
  // 盲标单源（设计评审 #8 · 2026-10-15）：修前按数组下标分配（`成员 ${65+i}`）——与
  // review.openBlind / debate.reveal 的确定性置换是两套算法，同一成员在看板与落线侧可能
  // 拿到两个不同的盲标（且下标盲标可由交卷顺序推断身份，正是 P2-13 洗掉的去匿名面）。
  // 现在与落线侧**同一份实现**（review.js 的 `盲标分配`）：线程参数 = 节点 id（debate.open
  // 调 reveal 用的就是它），名册 = 独立答案成员（debate.open 的 参与者=已交 同源数据）。
  // 输出仍是「成员 A/B/C」形态；确定性种子只认（节点 id + 排序名册）的集合，与投影时机无关。
  const 标表 = new Map(盲标分配(String(node.id ?? ''), 全量答案.map((a) => a.成员)).map((e) => [e.id, e.盲标]));
  const 答案 = 全量答案.map((a) => ({
    盲标: 标表.get(a.成员),
    ...(进度.齐
      ? {
          成员: a.成员,
          结论: a.结论,
          // 揭名后结论层也投影（2026-10-14 审查 P1-1）：§10 的判据字段，看板要看得见——
          // 盲评期不给（它同样是内容级信息），与结论同闸。
          结论层: a.结论层 ?? null,
          反例面: a.反例面 ?? [],
          产出物引用: a.产出物引用 ?? [],
        }
      : {}),
  }));
  // 判定输入 = **负责人的全量答案**（与遮罩无关的那一份）。它单独取个名字，是为了让
  // 「判定到底读了谁」在代码里就是一个可指认的东西（W3 批5）。
  // 过滤负责人 + 带结论层（2026-10-14 审查 P1-1/P1-2）：与 review.checkZeroDivergence
  // 同口径——非负责人垫卷不进判定池；缺结论层判据会退化成全文逐字比对。
  const 负责人 = node.负责人 ?? [];
  const 判定输入 = 全量答案
    .filter((a) => 负责人.includes(a.成员))
    .map((a) => ({ 成员: a.成员, 结论: a.结论, 结论层: a.结论层, 反例面: a.反例面 }));
  const 判定 = judgeZeroDivergence(判定输入);
  const 复核 = (node.复核经过 ?? []).at(-1) ?? null;
  return {
    节点: node.id,
    描述: node.描述,
    模式: node.模式 ?? null,
    揭名: 进度.齐,
    交卷: 进度,
    独立答案: 答案,
    分歧清单: 复核?.分歧清单 ?? [],
    反例面: 复核?.反例面 ?? [],
    // 零分歧也一起遮（W3 批3·2026-10-09）：它虽然只是「两份结论是否一致」，
    // 但未交齐时把「这两份一致」告诉观察者，本身就是内容级信息（盲评的意义在于互不可见）。
    // 判定照旧用**全量答案**现算，只是未齐时不投影这两个字段（齐后照给）。
    //
    // `零分歧判定基数`（W3 批5·2026-10-09）：未交齐时补一个**机械读数**——它由 `判定输入`
    // 算得（数「判定实际消费到几条带结论的答案」），**不含任何人的结论文本**，所以不破坏遮罩；
    // 但它让「判定读的是全量、不是遮罩后的行」这件事**可被断言打红**（遮罩行没有结论 ⇒ 基数塌成 0）。
    // 没有它，这条纪律在未交齐场景下没有任何可观察判据（复核实测：把判定改成读遮罩行仍然全绿）。
    //
    // `零分歧空卷数`（设计评审 F5 · 2026-10-15）：两份全空卷修前被折成「全票一致」触发
    // 人工抽检。空卷数是机械读数（不含结论文本，遮罩安全），未齐/齐后都投影——
    // 读的人看得见「为什么零分歧不判」。
    ...(进度.齐
      ? { 零分歧: 判定.零分歧, 零分歧依据: 判定.依据, 零分歧空卷数: 判定.空卷数 }
      : {
          零分歧判定基数: 判定输入.filter((a) => typeof a.结论 === 'string' && a.结论 !== '').length,
          零分歧空卷数: 判定.空卷数,
        }),
    复核三态: 复核?.三态 ?? null,
    复核者: 复核?.复核者 ?? null,
    // ⑮ 强制反对者（2026-10-10）：讨论开启时系统指定的那位。**没有讨论段就不给这个键**
    // （与「讨论小节没有就不画」同款，不给空壳）；有讨论段但当时没指定出来 ⇒ 空串，
    // 界面上是「有值才画」，空串与「没有这个键」在渲染层同效，但在投影层可区分。
    // 字段名沿用审计详情 `review.js` 的 `强制反对者`，同一件事只有一个名字。
    ...(node.讨论 ? { 强制反对者: node.讨论.反对者 ?? '' } : {}),
    ...(node.讨论 ? { 讨论: 讨论小节(node.讨论, 线程消息, 复核) } : {}),
  };
}

/**
 * 会审行的「讨论」小节（W2 2026-10-09）：{状态, 轮次/上限, 本轮消息数/上限,
 * 可收敛提示, 讨论未收敛标注}。读数全部现算（纯投影），预算用**开启时冻结的快照**。
 *
 * 「讨论未收敛」标注：讨论进行中就挂 true——复核对讨论是软约束（讨论中仍可 review），
 * 但读面板的人必须看得见「这条复核背后的讨论还没收敛」，否则「Lead 不收敛」
 * 会被静默漂过。不许把它做成 review 的硬闸（设计取舍已定）。
 *
 * @param {object} 讨论 node.讨论（fold 出的子状态）
 * @param {object[]} 线程消息
 * @param {object|null} 复核 最近的复核经过（可为 null）
 */
function 讨论小节(讨论, 线程消息, 复核) {
  // ①乙（2026-10-10）：预算名单与 `say()` / `round()` **同一份**（`预算名单()` = 参与者 ∪ 反对者），
  // 面板上的「本轮消息数 x/y」才与闸的读数是一回事（名单外发件不占预算）。
  const 本轮 = 本轮发言(线程消息, 预算名单(讨论));
  const 提示 = 可收敛判定(本轮, 讨论.参与者 ?? []);
  const 未收敛 = 讨论.状态 === '讨论中';
  return {
    状态: 讨论.状态,
    轮次: `${讨论.轮次 ?? 0}/${讨论.轮次上限 ?? '?'}`,
    本轮消息数: `${本轮.length}/${讨论.预算快照?.每轮消息上限 ?? '?'}`,
    可收敛: 提示.可收敛,
    可收敛说明: 提示.说明,
    ...(未收敛 ? { 讨论未收敛: true } : {}),
    ...(复核 && 未收敛 ? { 复核时讨论未收敛: true } : {}),
    表态消息id: 讨论.表态消息id ?? null,
  };
}
