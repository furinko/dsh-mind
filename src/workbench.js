/** 任务状态 → 分组计数用的桶。 */
const 进行中 = new Set(['已派发', '执行中']);

/**
 * 投影出一份完整视图。
 *
 * @param {{
 *   项目: string,
 *   节点?: object[],
 *   审计尾?: object[],
 *   成员?: object[],
 *   岗位?: object[],
 *   升级挂起?: object[],
 *   探针?: object,
 *   策略?: object,
 *   记忆?: object,
 *   线程?: object[],
 *   项目清单?: { 当前: string|null, 项: object[] },
 *   能力?: object[],
 *   岗位?: object[],
 *   实例计数?: object,
 *   岗位闲置?: Record<string, {在岗实例: number, 封存实例: number, 最近派发于: string|null}>,
 *   实例活动?: Record<string, {最近活动于: string|null, 活动条数: number}>,
 *   生成于?: string,
 * }} input
 * @returns {object} 视图；调用方不得把它写回磁盘。
 */
export function projectWorkbench(input) {
  const 节点 = input.节点 ?? [];
  const 待决 = 节点.filter((n) => n.状态 === '待决');
  const 升级 = 节点.filter((n) => n.升级);
  const 探针 = input.探针 ?? { 状态: '未知', 结果: [] };
  const 见红 = (探针.结果 ?? []).filter((r) => r.状态 === '红');
  // 会审讨论段（W2）：线程消息由组装层喂进来（讨论消息[nodeId]），投影自己算读数。
  const 讨论消息 = input.讨论消息 ?? {};
  // 会审线程名单（⑦ 消息总线遮罩用）：**与会审行同口径**（`负责人>1 || 独立答案>0`，
  // 见下面 `会审` 那一块）**并上**「开过讨论的节点」。两者取并集，各自堵一种漏：
  //
  //  ① 只装「已开讨论」的节点 ⇒ **未交齐的会审节点线程不遮**：`bus_send` 往 `线程=节点id`
  //     落一条「交卷 + 结论」是允许的（`test/debate-guards.test.js` 的「负责人自己的任务线程
  //     ⇒ 放行」钉着这条），而会审行此时只有盲标 ⇒ 同一个面板「会审行看不见、总线行原样画出」。
  //     判据是「揭名之前不给内容」，与线程有没有开讨论无关，所以会审形状必须进名单。
  //  ② 会审形状的节点一旦开了讨论，它**全部**线程（含讨论线程）都已由 ① 覆盖；
  //     `n.讨论` 那一路保留给「开了讨论但形状读起来不是会审」的边角（口径取并集，不取替换）。
  //
  // 键一律走单源 `线程等价键()`：落线路径 `busThread()` 直接 join 文件系统，而本部署在 NTFS
  // （大小写不敏感）⇒ 判定用精确键而落线不敏感 ⇒ `节点id.toUpperCase()` 先建线就是一条旁路
  // （`src/paths.js` 的函数注释点名要求判定侧不许再发明第二套）。集合与查询**两端**都用它。
  const 会审线程集合 = new Set(
    节点
      .filter((n) => n.讨论 || (n.负责人 ?? []).length > 1 || (n.独立答案 ?? []).length > 0)
      .map((n) => 线程等价键(n.id)),
  );

  return {
    项目: input.项目,
    生成于: input.生成于 ?? null,
    边界: { 只读: true, 说明: '工作台是投影：它不存储、不做讨论、不做权威记录。' },

    // 一行状态条：够判断「现在能不能干活」，不需要更多。
    状态条: {
      // 错误原文两个键名都认：投影输入是 `policy.describe()` 那份（键名 `error`），
      // 而投影字段名是中文 `错误`。只读其中一个曾经让面板**恒 null** ——
      // 闸不在位时看不到原因，只能靠去翻 `/mind status`（那是「面板看不见」的真缺陷）。
      闸: {
        在位: input.策略?.healthy === true,
        规则数: (input.策略?.rules ?? []).length,
        错误: input.策略?.错误 ?? input.策略?.error ?? null,
      },
      介入度: input.策略?.介入度 ?? '未知',
      失联: 失联态(input.策略?.失联),
      失联详情: 失联详情(input.策略?.失联),
      探针: { 状态: 探针.状态 ?? '未知', 见红: 见红.map((r) => r.探针), 恒红: 探针.恒红 === true, 恒绿: 探针.恒绿 === true },
    },

    // 设计里唯一点名要投影的东西，所以排在最前：主子只需要看这一块。
    待你决定: 收集待你决定({ 待决, 升级, 见红, 升级挂起: input.升级挂起 ?? [] }),

    任务: {
      总数: 节点.length,
      计数: {
        待派发: 节点.filter((n) => n.状态 === '待派发').length,
        进行中: 节点.filter((n) => 进行中.has(n.状态)).length,
        已交卷: 节点.filter((n) => n.状态 === '已交卷').length,
        已采纳: 节点.filter((n) => n.状态 === '已采纳').length,
        已打回: 节点.filter((n) => n.状态 === '已打回').length,
        未验: 节点.filter((n) => n.状态 === '未验').length,
        // 已结账（W3 批3）：环路的终态之一。不报它会出现「总数 5、各桶加起来 4」——
        // 少掉的那条不是"已结账"，而是"看起来不存在"。
        已结账: 节点.filter((n) => n.状态 === '已结账').length,
        待决: 待决.length,
      },
      节点: 节点.map((n) => 任务行(n, input.实例活动)),
    },

    会审: 节点.filter((n) => (n.负责人 ?? []).length > 1 || (n.独立答案 ?? []).length > 0).map((n) => 会审行(n, 讨论消息[n.id] ?? [])),

    // 记忆读数：宿主没给就不装懂（null），给了就原样投影——数字由 MemoryService.activity 保证真实。
    记忆: input.记忆
      ? {
          存量: input.记忆.存量合计 ?? null,
          近段: {
            窗口天: input.记忆.窗口天 ?? null,
            新增: input.记忆.新增合计 ?? null,
            晋升: input.记忆.晋升 ?? null,
          },
          // 按类构成（2026-10-13 重做·图谱/记忆页）：`activity()` 已经现算这一项，
          // 此前只留在服务层 ⇒ 面板画不出「记忆都是什么」。**只搬计数，不搬条目正文**
          // （正文出口是对话里的 memory_query；面板不承担内容陈列）。
          按类: input.记忆.按类 ?? null,
        }
      : null,

    // 能力 × 岗位接线（2026-10-13 重做·图谱）：
    // 「能力卡声明的适用岗位」与「岗位卡 个体L2 的实际引用」是两个真源，面板把它们画在一起
    // ⇒ 「发卡 ≠ 接线」这件事第一次有了可见面（此前只能在事后靠人回忆发现）。
    //
    // 三条纪律：
    //  ① **剥掉 `path`**：`capability.list()` 给的是本机绝对路径，投影不许把它带出去。
    //  ② **来源/同名照实带**：双区同名（`['私有','出厂']`）是「生效的是哪份、另外还有哪份」的
    //     唯一读数，吞掉它等于把一处需要人拍板的分歧变成静默覆盖。
    //  ③ 宿主没给 ⇒ `null`（不装懂）：与 记忆 / 项目清单 同款。凭空造一份空表会让面板
    //     把「宿主没给」画成「组织里一张卡都没有」。
    能力: Array.isArray(input.能力)
      ? input.能力.map((c) => ({
          id: c.id ?? c.名 ?? null,
          来源: c.来源 ?? null,
          适用岗位: strList(c.适用岗位),
        })).filter((c) => c.id !== null)
      : null,

    岗位: Array.isArray(input.岗位)
      ? input.岗位.map((r) => ({
          id: r.id ?? null,
          来源: r.来源 ?? null,
          同名: strList(r.同名),
          摘要: r.摘要 ?? '',
          能力引用: strList(r.能力引用),
        })).filter((r) => r.id !== null)
      : null,

    // 实例计数：岗位 → {在岗, 封存}。只给计数，**不给实例 id**（图谱上岗位是节点，
    // 实例是它的规模，不是可点对象）。宿主没给 ⇒ null。
    实例计数: input.实例计数 && typeof input.实例计数 === 'object' ? input.实例计数 : null,

    // 岗位闲置（派活闭环 2026-10-15）：岗位 → {在岗实例, 封存实例, 最近派发于}。
    // 原样投影（组装层 org.js 跨项目现算），「闲置与否」的判定留给读者——投影报读数不报结论。
    // 宿主没给 ⇒ null（不装懂）。治理面：成员切片不给（与 实例计数 同族）。
    岗位闲置: input.岗位闲置 && typeof input.岗位闲置 === 'object' ? input.岗位闲置 : null,

    审计尾: (input.审计尾 ?? []).map((row) => ({
      时间: row.时间,
      动作: row.动作,
      主体: row.主体?.id ?? row.主体,
      结果: row.结果,
      档位: row.档位,
      告警: row.告警 === true,
    })),

    // 项目清单（2026-10-11，主权者指令「修」）：各项目键 + 规模，供界面说清
    // 「你现在看的是哪个项目、还有哪些项目有账」。计数由组装层现算（`org.projectList`），
    // 投影只搬运；宿主没给就 `null`（不装懂）。
    项目清单: input.项目清单
      ? {
          当前: input.项目清单.当前 ?? null,
          项: (input.项目清单.项 ?? []).map((p) => ({
            项目: p.项目,
            任务: p.任务 ?? 0,
            线程: p.线程 ?? 0,
            未投递: p.未投递 ?? 0,
            最近于: p.最近于 ?? null,
          })),
        }
      : null,

    // ⑦（2026-10-11）：消息总线——**全部**有消息的线程（不只未投递）：主人要一眼看见
    // 「有没有人想说话」，未投递由看板高亮。盲评保护：**会审节点**（负责人>1 或有独立答案，
    // 与会审行同口径）与**开过讨论的节点**，在揭名之前它的**所有**线程都不给正文与发件 ——
    // 会审区已按盲标口径投影读数，这里再给正文等于把「谁说了什么」泄给未交齐的观察者
    // （遮罩做在投影层，与独立答案同款纪律）。判定键走单源 `线程等价键()`：与落线路径
    // `busThread()` 同一个等价类（NTFS 大小写不敏感），不许自己再发明一套（见 paths.js）。
    消息总线: (input.线程 ?? []).map((t) => (
      会审线程集合.has(线程等价键(t.线程))
        ? { 线程: t.线程, 条数: t.条数, 未投递: t.未投递, 会审讨论段: true }
        : { 线程: t.线程, 条数: t.条数, 未投递: t.未投递, 最新: t.最新 ?? [] }
    )),
  };
}

/**
 * 成员只读自己任务那片（§7）。
 *
 * 这条不是「少给点信息」的礼貌，而是 §7.5 项目隔离之外的**岗位内隔离**：
 * 一个成员不该看见别人的中间结果，否则独立会审就不是独立的。
 *
 * @param {object} view `projectWorkbench` 的输出
 * @param {{ id: string, kind: string, roleId?: string }} 读者
 * @returns {object}
 */
export function sliceForViewer(view, 读者) {
  if (读者?.kind !== '成员') {
    return { ...view, 视图: 读者?.kind === '复核者' ? '只读全量（复核者需要看到分歧清单）' : '全量' };
  }
  const 我的 = view.任务.节点.filter((n) => (n.负责人 ?? []).includes(读者.id) || (n.负责人 ?? []).includes(读者.roleId));
  const 我的id = new Set(我的.map((n) => n.id));
  return {
    ...view,
    任务: { ...view.任务, 节点: 我的 },
    待你决定: view.待你决定.filter((item) => item.节点 && 我的id.has(item.节点)),
    会审: view.会审.filter((a) => 我的id.has(a.节点)),
    审计尾: view.审计尾.filter((row) => row.主体 === 读者.id),
    // 能力 × 岗位接线（2026-10-13 重做）：**成员的职务结构不给**。
    // 理由与「成员只读自己任务那片」同源：谁看得到哪张能力卡、哪些岗位缺接线，是组织的
    // 治理面（Lead/主权者的判断输入），不是成员干活需要的那片。给 `null` 而不是空表——
    // 「没给」与「组织里没有」必须分得开，否则成员面板会把治理面画成「空图」。
    能力: null,
    岗位: null,
    实例计数: null,
    岗位闲置: null,
    // ⑦：成员切片不给总线正文与发件（「只读自己那片」——他人发言不是自己那片）；
    // 规模行保留，让成员看得见「有线程在说话」而不看见内容。
    消息总线: (view.消息总线 ?? []).map((t) => ({
      线程: t.线程,
      条数: t.条数,
      未投递: t.未投递,
      ...(t.会审讨论段 ? { 会审讨论段: true } : {}),
    })),
    视图: '只读自己任务那片',
  };
}

/**
 * 状态条的失联态：**四态字符串**，不是布尔。
 *
 * 为什么不能是布尔：布尔装不下「关了」这件事 —— `lost === false` 同时表示
 * 「主权者一直在」与「这个机制被停掉了」，读的人分不清这两件完全不同的事。
 * Batch 2 之前 `状态条.失联` 就是布尔，于是**关了开关反而显示成「没失联」**，
 * 看上去和「主权者一直在」一模一样 —— 那就是这条契约要修的缺陷。
 *
 * 四态取值的判据（顺序即优先级）：
 *  - `已关闭` ＝ `presence().已关闭 === true`（开关被关掉了，**先判它**，否则关了会被当成在位）；
 *  - `已失联` ＝ 超期（`lost === true`）；
 *  - `在位`   ＝ 有读数且明确没失联（`lost === false`）；
 *  - `未知`   ＝ 上层没给策略读数（**宿主没给 ≠ 正常**），或读数形状读不出结论。
 *
 * @param {object|undefined|null} 读数 `policy.presence()` 的读数
 * @returns {'在位'|'已失联'|'已关闭'|'未知'}
 */
function 失联态(读数) {
  if (!读数 || typeof 读数 !== 'object') return '未知';
  if (读数.已关闭 === true) return '已关闭';
  if (读数.lost === true) return '已失联';
  if (读数.lost === false) return '在位';
  return '未知';
}

/**
 * 失联的**读数细节**：把 `presence()` 里那几个来源/坏值标记原样带出来。
 *
 * 为什么不能只给一个四态字：读的人问的下一个问题是「凭什么」——
 * 生效期限是多少、这个值来自哪一层、我说的那个值是不是被判成不合法了。
 * 这些答案 Batch 1.5 已经算出来了，却只留在 `describe()` 里，工作台上看不见。
 *
 * **读不出结论就报 `null`，不许报 `false`**（这条是 Batch 2.5 补的）：布尔 `false` 是一个
 * **结论**（「没失联」/「没关」/「值合法」），而「读数缺失」或「形态读不出」没有任何结论 ——
 * 给 `false` 会让只读 `详情.lost` 的消费者把「未知」读成「在位」。三个布尔与四态必须互相一致：
 * 四态 `'未知'` ⇒ `已关闭` / `lost` 都是 `null`；四态有结论 ⇒ 它们才是布尔。
 *
 * @param {object|undefined|null} 读数 `policy.presence()` 的读数
 * @returns {object} 读不出结论处一律 `null` / `'未知'`，不给「看起来正常」的默认值
 */
function 失联详情(读数) {
  if (!读数 || typeof 读数 !== 'object') {
    return {
      读数: '缺失',
      说明: '宿主没有给策略读数：未知 ≠ 正常（没读到不许显示成在位）。',
      已关闭: null,
      lost: null,
      hours: null,
      since: null,
      deadline: null,
      生效响应期限小时: null,
      响应期限小时来源: '未知',
      失联限制来源: '未知',
      值不合法: null,
    };
  }
  const 态 = 失联态(读数);
  /** 四态有结论（在位 / 已失联 / 已关闭）⇒ 两个布尔才有意义；`'未知'` ⇒ 都是 `null`。 */
  const 有结论 = 态 !== '未知';
  return {
    读数: 态,
    已关闭: 读数.已关闭 === true ? true : (有结论 ? false : null),
    lost: 读数.lost === true ? true : (有结论 ? false : null),
    hours: Number.isFinite(读数.hours) ? 读数.hours : null,
    since: 读数.since ?? null,
    deadline: 读数.deadline ?? null,
    生效响应期限小时: Number.isFinite(读数.生效响应期限小时) ? 读数.生效响应期限小时 : null,
    响应期限小时来源: 读数.响应期限小时来源 ?? '未知',
    失联限制来源: 读数.失联限制来源 ?? '未知',
    // 这个布尔只说「你写的值不合法」这一件事：读数没给结论 ⇒ null，给了才照抄。
    值不合法: typeof 读数.值不合法 === 'boolean' ? 读数.值不合法 : null,
    // 坏值才带原值：合法值带个 `原值: null` 只会让读的人以为「有东西不合法」。
    ...(读数.值不合法 === true ? { 原值: 读数.原值 ?? null, 原值来源: 读数.原值来源 ?? '未知' } : {}),
    ...(读数.不合法说明 ? { 不合法说明: 读数.不合法说明 } : {}),
    // 「算不出确定结论」的原因也要带上（例如 lastInteraction 贴着 Date 上界）：
    // 只给 `deadline: null` 而不说为什么，读的人会以为「没有期限」。
    ...(读数.判定说明 ? { 判定说明: 读数.判定说明 } : {}),
  };
}

/**
 * 字符串数组的**形状守卫**：非数组 ⇒ `[]`，元素只留字符串。
 *
 * 为什么不让它 `null`：这些字段在渲染层是「列出节点/引用」的输入，`[]` 与 `null` 在
 * 「有没有这一格数据」上是两件事——但**上游有没有给整个块**已经由外层判过了
 * （`input.能力 === undefined ⇒ null`），到了元素这一层再缺，就是「这一行没有引用」。
 */
function strList(value) {
  if (!Array.isArray(value)) return [];
  return value.filter((x) => typeof x === 'string' && x !== '');
}

